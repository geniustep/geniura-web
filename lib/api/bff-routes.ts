export function allowedBackendPath(requestPath: string, method: string): string | null {
  const candidate = requestPath.replace(/\/$/, "");
  const actual = candidate.split("/");
  if (actual.length > 18 || candidate.length > 1500) return null;
  for (const [pattern, methods] of Object.entries(publicApiRoutes)) {
    if (!methods.includes(method)) continue;
    const expected = pattern.replace(/\/$/, "").split("/");
    if (expected.length !== actual.length) continue;
    const matched = expected.every((segment, i) =>
      segment.startsWith("{") && segment.endsWith("}")
        ? /^[A-Za-z0-9_.~:-]{1,512}$/.test(actual[i] ?? "")
        : segment === actual[i],
    );
    if (matched) return pattern.endsWith("/") ? `${candidate}/` : candidate;
  }
  return null;
}
